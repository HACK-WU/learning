#!/bin/bash
# 专项维度核查：B1-B8（经验/手册）+ C1-C7（场景库）+ 手册硬特征
BASE=/mnt/d/projects/learning/surrealdb
cd "$BASE" || exit 1

echo "===== 09 手册硬特征核查 ====="
N09=$(grep -c '^## .*症状 [0-9]*' 09-排障速查手册.md)
echo "-- 症状条目数: $N09"
echo "-- 特征1 症状倒查索引: $(grep -c '症状倒查索引' 09-排障速查手册.md) (期望>=1)"
echo "-- 特征2 「一眼识别」: $(grep -c '^\*\*一眼识别\*\*' 09-排障速查手册.md) / $N09"
echo "-- 特征3 「止血」行:   $(grep -c '^| \*\*止血\*\*' 09-排障速查手册.md) / $N09"
echo "-- 特征4 「若无效」行: $(grep -c '^| 若无效' 09-排障速查手册.md) / $N09"
echo "-- 特征5 「原理」回指: $(grep -c '^\*\*原理\*\*\|^> \*\*原理\*\*' 09-排障速查手册.md) / $N09"
echo "-- 「预防」行:        $(grep -c '^\*\*预防\|^> \*\*预防' 09-排障速查手册.md) / $N09"
echo "-- 紧急度分级: RED=$(grep -c '^## 🔴' 09-排障速查手册.md) YELLOW=$(grep -c '^## 🟡' 09-排障速查手册.md) WHITE=$(grep -c '^## ⚪' 09-排障速查手册.md)"

echo ""
echo "===== 08 五段式完整性核查 ====="
N08=$(grep -c '^### 故障模式' 08-实战经验.md)
echo "-- 故障模式数: $N08"
for kw in '症状（可观测）' '根因' '排查路径' '修复' '预防'; do
  echo "  「$kw」: $(grep -cF -- "**$kw" 08-实战经验.md) / $N08"
done
echo "-- 回指手册条目: $(grep -c '对应速查条目' 08-实战经验.md) / $N08"

echo ""
echo "===== 08 证据溯源核查 ====="
grep -o '【实测】\|【官方】\|【公认】\|⏳ 置信度' 08-实战经验.md | sort | uniq -c | sort -rn

echo ""
echo "===== 10 场景库硬要求核查 ====="
echo "-- 场景数: $(grep -c '^## 场景 ' 10-场景解法库.md)"
echo "-- 解法一览: $(grep -c '### 解法一览' 10-场景解法库.md)"
grep '### 解法一览' 10-场景解法库.md | sed 's/### 解法一览（/  /; s/个.*//'
echo "-- 每场景解法数（表格数据行，应 >=3）:"
awk '/^## 场景 /{s=$0} /^### 解法一览/{f=1;print "  "s;next} /^### /{f=0} f&&/^\| \*\*[A-E] ·/{c++} /^## 场景 /{if(c>0){print "     解法数:",c; c=0}} END{if(c>0)print "     解法数:",c}' 10-场景解法库.md

echo ""
echo "===== 10 五件套核查 ====="
echo "-- 先想30秒折叠: $(grep -c '先想 30 秒' 10-场景解法库.md) (期望 8)"
echo "-- 展开解法折叠: $(grep -c '✅ 展开解法' 10-场景解法库.md) (期望 8)"
echo "-- 推荐路径:     $(grep -c '### 推荐路径' 10-场景解法库.md) (期望 8)"
echo "-- 知识点挂钩:   $(grep -c '### 知识点挂钩' 10-场景解法库.md) (期望 8)"
echo "-- 不适用:       $(grep -c '^### 不适用' 10-场景解法库.md) (期望 8)"
echo "-- 做错会踩的坑: $(grep -c '做错会踩的坑' 10-场景解法库.md) (期望 8)"

echo ""
echo "===== 10 知识点回指课时 ====="
grep -o '课 [0-9]*' 10-场景解法库.md | sort -u -t' ' -k2 -n | tr '\n' ' '
echo ""
echo "-- 引用实战项目: $(grep -c 'projects/' 10-场景解法库.md) 处"

echo ""
echo "===== 三份产物核查时点标注 ====="
for f in 08-实战经验.md 09-排障速查手册.md 10-场景解法库.md final-课程手册.md; do
  echo "-- $f: 核查于=$(grep -c '核查于 2026-09' $f) 行数=$(wc -l < $f)"
done

echo ""
echo "===== final-课程手册 结构核查 ====="
echo "-- 知识点表行数(应为40): $(grep -cE '^\| [0-9]+\.[0-9]+ \|' final-课程手册.md)"
echo "-- 一句话记住条数: $(grep -c '一句话记住' final-课程手册.md)"
echo "-- Mermaid 图: $(grep -c '```mermaid' final-课程手册.md) (应为偶数*2, 围栏开+关)"

echo ""
echo "===== 08 静默失败清单 ====="
echo "-- 清单条目数: $(grep -cE '^\| [0-9]+ \| ' 08-实战经验.md)"
echo "-- 故障模式编号引用(01-10): $(grep -o '故障模式 [0-9]*' 08-实战经验.md 09-排障速查手册.md 10-场景解法库.md | sort -u | tr '\n' ' ')"
