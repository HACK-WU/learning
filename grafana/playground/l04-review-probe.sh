#!/usr/bin/env bash
# 课 4 双视角评审用核查脚本
# 纪律：每条「缺失/错误/遗漏」判定，必须先回读原文或用脚本核验
set -u

F="/mnt/d/projects/learning/grafana/stages/2-查得到/lessons/lesson-04-查询编辑器与数据源协议：一次查询的完整旅程.md"

echo "=========================================================="
echo " 课 4 评审核查：逐条回读原文核验"
echo "=========================================================="

echo ""
echo "### Learner 视角：读者照抄能跑通吗 ###"
echo ""

echo "Q1. 正文提到的每个脚本，是否都给了完整执行命令？"
grep -n 'wsl -d Ubuntu' "$F" | sed 's/^/    /'

echo ""
echo "Q2. 脚本首次运行是否有前置说明（拉镜像/环境前提）？"
grep -n -B1 -A2 '环境前提\|首次运行\|需要拉取' "$F" | head -20

echo ""
echo "Q3. 实验预期结果是否给了「判据」而不仅是「现象」？"
grep -n '预期看到\|判断.*看\|关键证据' "$F" | head -20

echo ""
echo "### Pedagogy 视角 ###"
echo ""

echo "Q4. 认知冲突是否指向真问题（文档矛盾 vs 编造冲突）？"
grep -n '3 distinct modes\|two modes\|PR #53062\|自相矛盾' "$F" | head

echo ""
echo "Q5. 六要素是否每个知识点都齐全（4.1 报 7、4.2 报 8 需查明多出的是谁）？"
echo "  --- 4.1 区间的 #### 小节 ---"
awk '/^### 知识点 4\.1/{f=1} /^### 知识点 4\.2/{f=0} f&&/^#### /{print "    "$0}' "$F"
echo "  --- 4.2 区间的 #### 小节 ---"
awk '/^### 知识点 4\.2/{f=1} /^### 知识点 4\.3/{f=0} f&&/^#### /{print "    "$0}' "$F"
echo "  --- 4.3 区间的 #### 小节 ---"
awk '/^### 知识点 4\.3/{f=1} /^## 🛠 第四幕/{f=0} f&&/^#### /{print "    "$0}' "$F"

echo ""
echo "### 数据事实核对 ###"
echo ""
echo "Q6. 正文引用的实测数字，与探测脚本输出是否一致？"
echo "  正文中出现的数字："
grep -o '30000\|calculatedMinStep[^ ]*\|15000\|1m0s\|502\|400' "$F" | sort | uniq -c | sort -rn | head -12

echo ""
echo "Q7. 是否有「未实测」但写成了确定语气的地方？"
grep -n '大概率\|推断\|应该会\|可能会' "$F" | head

echo ""
echo "Q8. 与课 3 结论是否冲突（变量替换位置）？"
grep -n '前端替换\|后端替换\|原样透传\|原样保留' "$F" | head

echo ""
echo "Q9. 端口/uid/版本 是否与档案一致？"
echo "  档案值：端口 9201 / uid afx7x6dx803y8e / Grafana 13.2.1 / 插件 13.1.7"
grep -c '9201' "$F" | sed 's/^/    9201 出现 /'
grep -c 'afx7x6dx803y8e' "$F" | sed 's/^/    uid 出现 /'
grep -c '13\.1\.7' "$F" | sed 's/^/    插件版本 13.1.7 出现 /'

echo ""
echo "=========================================================="
