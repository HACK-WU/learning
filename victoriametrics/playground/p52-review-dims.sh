#!/bin/bash
# 专项维度核查：B1-B8（经验/手册）+ C1-C7（场景库）+ 手册五硬特征
BASE=/mnt/d/projects/learning/victoriametrics
cd "$BASE" || exit 1

echo "===== 09 手册五硬特征核查 ====="
N09=$(grep -c '^## .*症状 [0-9]*' 09-排障速查手册.md)
echo "-- 特征1 症状倒查索引: $(grep -c '症状倒查索引' 09-排障速查手册.md) (期望>=1)"
echo "-- 特征2 「一眼识别」: $(grep -c '^\*\*一眼识别\*\*' 09-排障速查手册.md) / 症状条目 $N09"
echo "-- 特征3 「止血」行:   $(grep -c '| \*\*止血\*\*' 09-排障速查手册.md) / $N09"
echo "-- 特征5 「若无效」行: $(grep -c '| 若无效' 09-排障速查手册.md) / $N09"
echo "-- 特征5 「原理」回指: $(grep -c '^\*\*原理\*\*' 09-排障速查手册.md) / $N09"
echo "-- 「预防」行:        $(grep -c '^\*\*预防\*\*' 09-排障速查手册.md) / $N09"
echo "-- 紧急度分级: 🔴$(grep -c '^## 🔴' 09-排障速查手册.md) 🟡$(grep -c '^## 🟡' 09-排障速查手册.md) ⚪$(grep -c '^## ⚪' 09-排障速查手册.md)"

echo ""
echo "===== 08 五段式完整性核查 ====="
N08=$(grep -c '^### 故障模式' 08-实战经验.md)
echo "-- 故障模式数: $N08"
for kw in '症状（可观测）' '根因' '排查路径' '修复' '预防'; do
  echo "  「$kw」: $(grep -cF -- "- **$kw" 08-实战经验.md) / $N08"
done
echo "-- 回指手册条目: $(grep -c '对应速查条目' 08-实战经验.md) / $N08"

echo ""
echo "===== 08 证据溯源核查（每条是否有依据标注） ====="
grep -o '课 [0-9]* 实测\|实战项目实测\|官方文档\|核查于 2026-09\|课 [0-9]* / \|实战项目（' 08-实战经验.md | sort | uniq -c | sort -rn | head -15

echo ""
echo "===== 10 场景库硬要求核查 ====="
echo "-- 场景数: $(grep -c '^## 场景 ' 10-场景解法库.md)"
echo "-- 解法一览: $(grep -c '### 解法一览' 10-场景解法库.md)"
grep '### 解法一览' 10-场景解法库.md | sed 's/### 解法一览（/  /; s/个.*//' 
echo "-- 每个场景的解法行数（应 >=3 个解法，即表格至少 3 行数据）:"
awk '/^## 场景 /{s=$0} /^### 解法一览/{f=1;print "  "s;next} /^### /{f=0} f&&/^\| \*\*[A-E] ·/{c++} /^## 场景 /{if(c>0){print "     解法数:",c; c=0}} END{if(c>0)print "     解法数:",c}' 10-场景解法库.md

echo ""
echo "===== 10 知识点挂钩是否回指具体课时 ====="
grep -o '课 [0-9]*' 10-场景解法库.md | sort -u | tr '\n' ' '
echo ""
grep -c '实战项目' 10-场景解法库.md

echo ""
echo "===== 三份产物的置信度/核查标注 ====="
echo "-- 08 含核查说明: $(grep -c '核查于 2026-09' 08-实战经验.md)"
echo "-- 10 含核查说明: $(grep -c '核查于 2026-09' 10-场景解法库.md)"
echo "-- 09 含核查说明: $(grep -c '核查于 2026-09' 09-排障速查手册.md)"
echo "-- 推演标注: 08:$(grep -c '推演' 08-实战经验.md) 10:$(grep -c '推演' 10-场景解法库.md)"
